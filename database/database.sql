-- Создание таблицы товаров
CREATE TABLE public.tovar (
    tovar_id SERIAL PRIMARY KEY,
    tovar_article TEXT NOT NULL,
    tovar_name TEXT NOT NULL,
    tovar_ednica TEXT,
    tovar_cost REAL NOT NULL,
    tovar_deliveryman TEXT,
    tovar_creator TEXT,
    tovar_category TEXT,
    tovar_sale INTEGER DEFAULT 0,
    tovar_count INTEGER NOT NULL,
    tovar_information TEXT,
    tovar_picture TEXT
);

-- Создание таблицы пунктов выдачи
CREATE TABLE public.pvz (
    pvz_id SERIAL PRIMARY KEY,
    pvz_address TEXT NOT NULL
);

-- Создание таблицы клиентов
CREATE TABLE public.client (
    user_role TEXT NOT NULL,
    user_name TEXT NOT NULL,
    user_login TEXT PRIMARY KEY,
    user_password TEXT NOT NULL
);

-- Создание таблицы заказов
CREATE TABLE public.orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_article TEXT NOT NULL,
    order_create_date DATE NOT NULL,
    order_delivery_date DATE,
    order_pvz_id_fk INTEGER NOT NULL,
    order_client_name TEXT NOT NULL,
    order_code INTEGER NOT NULL,
    order_status TEXT NOT NULL,
    CONSTRAINT fk_orders_pvz FOREIGN KEY (order_pvz_id_fk) REFERENCES public.pvz(pvz_id) ON DELETE CASCADE,
    CONSTRAINT fk_orders_client FOREIGN KEY (order_client_name) REFERENCES public.client(user_login) ON DELETE CASCADE
);

-- Создание связующей таблицы заказ-товар
CREATE TABLE public.order_tovar (
    order_id INTEGER NOT NULL,
    tovar_id INTEGER NOT NULL,
    count INTEGER NOT NULL CHECK (count > 0),
    CONSTRAINT pk_order_tovar PRIMARY KEY (order_id, tovar_id),
    CONSTRAINT fk_order_tovar_order FOREIGN KEY (order_id) REFERENCES public.orders(order_id) ON DELETE CASCADE,
    CONSTRAINT fk_order_tovar_tovar FOREIGN KEY (tovar_id) REFERENCES public.tovar(tovar_id) ON DELETE CASCADE
);

